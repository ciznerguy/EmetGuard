// נוסף בגרסה 3.
// מחלקת הבסיס של כל מחלקות הנתונים בפרויקט.
// לכל טבלה בבסיס הנתונים יש מזהה ראשי, ולכן המזהה מוגדר כאן פעם אחת,
// וכל מחלקה שמייצגת טבלה יורשת אותו במקום להגדיר אותו מחדש.
namespace Model
{
    // המחלקה מופשטת: אי אפשר ליצור ממנה עצם ישירות, רק ממחלקות שיורשות ממנה
    public abstract class BaseEntity
    {
        // המזהה הראשי של השורה בטבלה. בסיס הנתונים נותן אותו בזמן ההוספה
        public int Id { get; set; }

        // בנאי ריק, לעצם חדש שעוד אין לו מזהה.
        // הבנאים מוגנים, כך שרק מחלקות יורשות יכולות לקרוא להם
        protected BaseEntity() { }

        // בנאי שמקבל מזהה, לעצם שנשלף מבסיס הנתונים
        protected BaseEntity(int id)
        {
            Id = id;
        }
    }
}
